export function normalizeLanguage(value) {
  return value === 'zh' ? 'zh' : 'en';
}

export function inferLanguageFromAcceptLanguage(headerValue) {
  const header = String(headerValue || '').toLowerCase();
  return header.split(',').some((part) => part.trim().startsWith('zh')) ? 'zh' : 'en';
}

export function createTranslator(language) {
  const normalized = normalizeLanguage(language);
  return (key) => dictionaries[normalized][key] || dictionaries.en[key] || key;
}

